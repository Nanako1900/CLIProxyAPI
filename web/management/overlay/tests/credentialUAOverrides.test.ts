import { afterEach, describe, expect, mock, spyOn, test } from 'bun:test';
import type { AxiosAdapter } from 'axios';
import { apiClient } from '../src/services/api/client';
import {
  buildCredentialOverrideClearPatch,
  buildCredentialOverrideSavePatch,
  parseUALabClaudeCredentialHeaders,
  parseUALabCodexCredentialHeaders,
  userAgentPanelConnection,
} from '../src/services/api/userAgentPanel';

afterEach(() => mock.restore());

describe('per-account UA/UALab credential overrides', () => {
  test('parses Claude UALab YAML into per-account headers and rejects auto', () => {
    const yaml = `# Generated by UALab from CPA Claude runtime profile (mode: fixed)
upstream:
  claude:
    header-defaults:
      user-agent: "claude-cli/2.1.331 (external, sdk-cli)"
      package-version: "0.128.0"
      runtime-version: "v26.12.1"
      os: "MacOS"
      arch: "arm64"
      timeout: "600"
      extra-headers:
        "x-app": "cli"
      header-order:
        - User-Agent
`;
    const parsed = parseUALabClaudeCredentialHeaders(yaml);
    expect(parsed.error).toBeUndefined();
    expect(parsed.headers).toEqual({
      'User-Agent': 'claude-cli/2.1.331 (external, sdk-cli)',
      'X-Stainless-Package-Version': '0.128.0',
      'X-Stainless-Runtime-Version': 'v26.12.1',
      'X-Stainless-OS': 'MacOS',
      'X-Stainless-Arch': 'arm64',
      'X-Stainless-Timeout': '600',
    });

    expect(
      parseUALabClaudeCredentialHeaders(
        '# Generated by UALab\nupstream:\n  claude:\n    header-defaults:\n      user-agent: auto'
      ).error
    ).toBeDefined();
    expect(
      parseUALabClaudeCredentialHeaders(
        'upstream:\n  claude:\n    header-defaults:\n      user-agent: "claude-cli/2.1.331"'
      ).error
    ).toBeDefined();
  });

  test('parses Codex UALab YAML into per-account headers and rejects auto', () => {
    const yaml = `# Generated by UALab from local capture (tag: codex-cli)
oauth:
  providers:
    codex:
      header-defaults:
        user-agent: "codex-tui/0.172.0 (Mac OS 27.3.0; arm64) Apple_Terminal/489.11 (codex-tui; 0.172.0)"
        originator: "codex_tui"
        beta-features: "js_repl,apps"
        accept-encoding: "zstd,gzip"
`;
    const parsed = parseUALabCodexCredentialHeaders(yaml);
    expect(parsed.error).toBeUndefined();
    expect(parsed.headers).toEqual({
      'User-Agent':
        'codex-tui/0.172.0 (Mac OS 27.3.0; arm64) Apple_Terminal/489.11 (codex-tui; 0.172.0)',
      Originator: 'codex_tui',
      'X-Codex-Beta-Features': 'js_repl,apps',
      'Accept-Encoding': 'zstd,gzip',
    });

    expect(
      parseUALabCodexCredentialHeaders(
        '# Generated by UALab\noauth:\n  providers:\n    codex:\n      header-defaults:\n        user-agent: auto'
      ).error
    ).toBeDefined();
  });

  test('builds save patch clearing removed optional keys and clear patch restoring global inheritance', () => {
    const saved = buildCredentialOverrideSavePatch(
      'claude',
      {
        'User-Agent': 'claude-cli/2.1.331 (external, sdk-cli)',
        'X-Stainless-Package-Version': '',
      },
      {
        'User-Agent': 'claude-cli/2.1.322 (external, sdk-cli)',
        'X-Stainless-Package-Version': '0.127.0',
      }
    );
    expect(saved.error).toBeUndefined();
    expect(saved.headers).toEqual({
      'User-Agent': 'claude-cli/2.1.331 (external, sdk-cli)',
      'X-Stainless-Package-Version': '',
    });

    expect(
      buildCredentialOverrideSavePatch('codex', { 'User-Agent': 'auto' }).error
    ).toBeDefined();

    const cleared = buildCredentialOverrideClearPatch('codex', {
      'User-Agent': 'codex-tui/0.172.0',
      Originator: 'codex_tui',
    });
    expect(cleared).toEqual({
      'User-Agent': '',
      Originator: '',
      'X-Codex-Beta-Features': '',
      'Accept-Encoding': '',
    });
  });

  test('calls v8 /credentials and /credentials/fields endpoints on captured connection', async () => {
    const calls: { method: string; baseURL?: string; url?: string; body?: unknown }[] = [];
    const adapter: AxiosAdapter = async (request) => {
      calls.push({
        method: (request.method || '').toUpperCase(),
        baseURL: request.baseURL,
        url: request.url,
        body: request.data ? JSON.parse(request.data) : undefined,
      });
      return {
        data:
          request.url === '/credentials'
            ? {
                files: [
                  {
                    auth_index: 'idx-1',
                    name: 'claude-new.json',
                    label: 'Claude New',
                    provider: 'claude',
                    disabled: false,
                    runtime_only: false,
                  },
                  {
                    auth_index: 'idx-rt',
                    name: 'runtime-only.json',
                    provider: 'claude',
                    runtime_only: true,
                  },
                ],
              }
            : { status: 'ok' },
        status: 200,
        statusText: 'OK',
        headers: {},
        config: request,
      };
    };

    apiClient.setConfig({ apiBase: 'https://cpa.example/panel', managementKey: 'test-key' });
    const client = apiClient.captureConnection();
    spyOn(apiClient, 'captureConnection').mockReturnValue(client);
    const get = client.get.bind(client);
    const patch = client.patch.bind(client);
    spyOn(client, 'get').mockImplementation((url, options) => get(url, { ...options, adapter }));
    spyOn(client, 'patch').mockImplementation((url, body, options) =>
      patch(url, body, { ...options, adapter })
    );

    const conn = userAgentPanelConnection();
    const creds = await conn.listCredentials();
    expect(creds).toEqual([
      {
        authIndex: 'idx-1',
        name: 'claude-new.json',
        label: 'Claude New',
        provider: 'claude',
        disabled: false,
      },
    ]);

    await conn.saveCredentialOverride('claude-new.json', {
      'User-Agent': 'claude-cli/2.1.331 (external, cli)',
    });

    expect(calls).toEqual([
      {
        method: 'GET',
        baseURL: 'https://cpa.example/panel/v8/management',
        url: '/credentials',
        body: undefined,
      },
      {
        method: 'PATCH',
        baseURL: 'https://cpa.example/panel/v8/management',
        url: '/credentials/fields',
        body: {
          name: 'claude-new.json',
          headers: { 'User-Agent': 'claude-cli/2.1.331 (external, cli)' },
        },
      },
    ]);
  });
});
