func TestGeminiUserAgentV8Configuration(t *testing.T) {
	const agyUA = "google-genai-sdk/1.79.1 gl-go/go1.28-20261102-RC01 cl/1012564305 +298f53e483 X:fieldtrack,boringcrypto,nogolistexportnewformat"
	input := []byte(`# Generated by UALab from local capture (tag: agy)
upstream:
  gemini:
    header-defaults:
      user-agent: "  ` + agyUA + `  "
      api-client: "` + agyUA + `"
      accept-encoding: "gzip"
      force-http1: true
      header-order:
        - Host
        - User-Agent
        - Content-Length
        - Content-Type
        - X-Goog-Api-Client
        - X-Goog-Api-Key
        - Accept-Encoding
        - user-agent
`)
	if err := ValidateV8Config(input); err != nil {
		t.Fatal(err)
	}
	cfg, err := ParseConfigBytes(input)
	if err != nil {
		t.Fatal(err)
	}
	wantOrder := "Host,User-Agent,Content-Length,Content-Type,X-Goog-Api-Client,X-Goog-Api-Key,Accept-Encoding"
	if cfg.GeminiHeaderDefaults.UserAgent != agyUA || cfg.GeminiHeaderDefaults.APIClient != agyUA ||
		cfg.GeminiHeaderDefaults.AcceptEncoding != "gzip" || !cfg.GeminiHeaderDefaults.ForceHTTP1 ||
		strings.Join(cfg.GeminiHeaderDefaults.HeaderOrder, ",") != wantOrder {
		t.Fatalf("unexpected GeminiHeaderDefaults: %#v", cfg.GeminiHeaderDefaults)
	}

	parsed, err := ParseUALabGeminiYAML(string(input))
	if err != nil {
		t.Fatalf("ParseUALabGeminiYAML failed: %v", err)
	}
	if parsed.UserAgent != agyUA || strings.Join(parsed.HeaderOrder, ",") != wantOrder {
		t.Fatalf("unexpected ParseUALabGeminiYAML result: %#v", parsed)
	}

	path := filepath.Join(t.TempDir(), "config.yaml")
	if err := os.WriteFile(path, input, 0600); err != nil {
		t.Fatal(err)
	}
	if err := SaveConfigPreserveComments(path, cfg.ForAPIKey(), true); err != nil {
		t.Fatal(err)
	}
	out, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var node yaml.Node
	if err := yaml.Unmarshal(out, &node); err != nil {
		t.Fatal(err)
	}
	ua := yamlPath(node.Content[0], "upstream.gemini.header-defaults.user-agent")
	if ua == nil || ua.Value != agyUA {
		t.Fatalf("shared Gemini default did not round trip: %v", ua)
	}
}

func TestGeminiUserAgentRejectsInvalidAndAutoConfig(t *testing.T) {
	for _, data := range []string{
		`upstream: {gemini: {header-defaults: {user-agent: "bad\nheader"}}}`,
		`gemini-api-key: [{api-key: key, headers: {USER-agent: "bad\nheader"}}]`,
		`interactions-api-key: [{api-key: key, headers: {USER-agent: "bad\nheader"}}]`,
		`vertex-api-key: [{api-key: key, headers: {USER-agent: "bad\nheader"}}]`,
	} {
		if _, err := ParseConfigBytes([]byte(data)); err == nil || !strings.Contains(err.Error(), "printable ASCII") {
			t.Errorf("expected invalid User-Agent rejection for %s, got %v", data, err)
		}
	}

	for _, autoYAML := range []string{
		`upstream: {gemini: {header-defaults: {user-agent: auto}}}`,
		`upstream: {gemini: {header-defaults: {api-client: AUTO}}}`,
		`gemini-api-key: [{api-key: key, headers: {User-Agent: auto}}]`,
		`interactions-api-key: [{api-key: key, headers: {User-Agent: AUTO}}]`,
		`vertex-api-key: [{api-key: key, headers: {User-Agent: " auto "}}]`,
	} {
		if _, err := ParseConfigBytes([]byte(autoYAML)); err == nil || !strings.Contains(err.Error(), "does not support \"auto\"") {
			t.Errorf("expected auto rejection for %s, got %v", autoYAML, err)
		}
	}

	if _, err := ParseUALabGeminiYAML("upstream:\n  gemini:\n    header-defaults:\n      user-agent: \"x/1\"\n"); err == nil {
		t.Fatal("expected ParseUALabGeminiYAML to require # Generated by UALab marker")
	}
	if _, err := ParseUALabGeminiYAML("# Generated by UALab\nupstream:\n  gemini:\n    header-defaults:\n      user-agent: auto\n"); err == nil {
		t.Fatal("expected ParseUALabGeminiYAML to reject auto")
	}
}

func TestGeminiUserAgentConflictingHeaders(t *testing.T) {
	for _, provider := range []string{"gemini", "interactions", "vertex"} {
		for _, tc := range []struct {
			first, second string
			conflict      bool
		}{
			{"mytool/1", "auto", true}, {"USER/1", "user/1", true}, {" auto", "AUTO", true}, {" mytool/1", "mytool/1", false},
		} {
			raw := "api-keys: {" + provider + ": [{name: group, keys: [{api-key: key}], headers: {User-Agent: '" + tc.first + "', user-agent: '" + tc.second + "'}}]}"
			if err := ValidateV8Config([]byte(raw)); (err != nil) != tc.conflict {
				t.Errorf("ValidateV8Config(%q) returned %v", raw, err)
			}
			if _, err := ParseConfigBytes([]byte(raw)); (err != nil) != tc.conflict {
				t.Errorf("ParseConfigBytes(%q) returned %v", raw, err)
			}
		}
	}
}

func TestGeminiUserAgentRejectsConflictingGroupEvenWhenShadowed(t *testing.T) {
	raw := []byte(`api-keys: {gemini: [{name: group, headers: {User-Agent: fixed-a, user-agent: fixed-b}, keys: [{api-key: key, headers: {User-Agent: local}}]}]}`)
	if err := ValidateV8Config(raw); err == nil || !strings.Contains(err.Error(), "conflicting User-Agent") {
		t.Fatalf("conflict in group headers was accepted: %v", err)
	}
}

func TestStartupLoadMigratesLegacyGeminiAutoAndPreservesOtherProviders(t *testing.T) {
	raw := []byte(`config-version: 8
server:
  port: 8317
  server-id: 11111111-1111-4111-8111-111111111111
oauth:
  providers:
    codex:
      header-defaults:
        user-agent: auto
upstream:
  claude:
    header-defaults:
      user-agent: auto
  gemini:
    header-defaults:
      user-agent: auto
      api-client: AUTO
api-keys:
  gemini:
    - name: group-1
      headers:
        User-Agent: auto
        X-Keep: "1"
      keys:
        - api-key: key-inherit
        - api-key: key-1
          headers:
            user-agent: " AUTO "
            X-Key: "2"
  interactions:
    - name: inter-1
      keys:
        - api-key: inter-key
          headers:
            User-Agent: auto
  vertex:
    - name: vertex-1
      headers:
        User-Agent: auto
      keys:
        - api-key: vertex-key
`)
	// Strict parsing and V8 validation must continue rejecting Gemini "auto".
	if _, err := ParseConfigBytes(raw); err == nil || !strings.Contains(err.Error(), "does not support \"auto\"") {
		t.Fatalf("ParseConfigBytes should reject legacy Gemini auto, got %v", err)
	}
	if err := ValidateV8Config(raw); err == nil || !strings.Contains(err.Error(), "does not support \"auto\"") {
		t.Fatalf("ValidateV8Config should reject legacy Gemini auto, got %v", err)
	}

	// Startup in-memory parsing (plugin bootstrap / Home config) must strip legacy Gemini auto.
	bootCfg, errBoot := ParseStartupConfigBytes(raw)
	if errBoot != nil {
		t.Fatalf("ParseStartupConfigBytes() error = %v", errBoot)
	}
	if bootCfg.GeminiHeaderDefaults.UserAgent != "" || bootCfg.GeminiHeaderDefaults.APIClient != "" {
		t.Fatalf("expected cleared GeminiHeaderDefaults, got %#v", bootCfg.GeminiHeaderDefaults)
	}
	if bootCfg.CodexHeaderDefaults.UserAgent != "auto" || bootCfg.ClaudeHeaderDefaults.UserAgent != "auto" {
		t.Fatalf("expected Codex/Claude auto preserved, got codex=%q claude=%q", bootCfg.CodexHeaderDefaults.UserAgent, bootCfg.ClaudeHeaderDefaults.UserAgent)
	}

	// File startup loading must strip legacy Gemini auto and persist the migrated config.
	path := filepath.Join(t.TempDir(), "config.yaml")
	if errWrite := os.WriteFile(path, raw, 0600); errWrite != nil {
		t.Fatal(errWrite)
	}
	cfg, errLoad := LoadConfig(path)
	if errLoad != nil {
		t.Fatalf("LoadConfig() error = %v", errLoad)
	}
	if cfg.GeminiHeaderDefaults.UserAgent != "" || cfg.GeminiHeaderDefaults.APIClient != "" {
		t.Fatalf("expected cleared GeminiHeaderDefaults after LoadConfig, got %#v", cfg.GeminiHeaderDefaults)
	}
	if cfg.CodexHeaderDefaults.UserAgent != "auto" || cfg.ClaudeHeaderDefaults.UserAgent != "auto" {
		t.Fatalf("expected Codex/Claude auto preserved after LoadConfig, got codex=%q claude=%q", cfg.CodexHeaderDefaults.UserAgent, cfg.ClaudeHeaderDefaults.UserAgent)
	}
	if len(cfg.GeminiKey) != 2 || cfg.GeminiKey[0].Headers["X-Keep"] != "1" || cfg.GeminiKey[1].Headers["X-Key"] != "2" {
		t.Fatalf("unexpected GeminiKey headers after migration: %#v", cfg.GeminiKey)
	}
	for _, key := range cfg.GeminiKey {
		for name := range key.Headers {
			if strings.EqualFold(name, "User-Agent") {
				t.Fatalf("expected Gemini User-Agent auto header removed, got %#v", key.Headers)
			}
		}
	}

	// Persisted file on disk must now pass strict ParseConfigBytes and ValidateV8Config.
	migrated, errRead := os.ReadFile(path)
	if errRead != nil {
		t.Fatal(errRead)
	}
	if errStrict := ValidateV8Config(migrated); errStrict != nil {
		t.Fatalf("migrated config.yaml failed ValidateV8Config: %v\n%s", errStrict, string(migrated))
	}
	if _, errStrict := ParseConfigBytes(migrated); errStrict != nil {
		t.Fatalf("migrated config.yaml failed ParseConfigBytes: %v\n%s", errStrict, string(migrated))
	}

	// Remote upload preparation & seed comparison must also support legacy Gemini auto.
	prepared, errPrepare := PrepareConfigBytesForUploadWithOptional(raw, false)
	if errPrepare != nil {
		t.Fatalf("PrepareConfigBytesForUploadWithOptional() error = %v", errPrepare)
	}
	if !IsPreparedConfigFromSeed(raw, prepared) {
		t.Fatalf("IsPreparedConfigFromSeed returned false for migrated legacy Gemini auto config")
	}
}

func TestStartupLoadLegacyKeysAndReadOnlyFile(t *testing.T) {
	raw := []byte(`port: 8317
gemini-header-defaults:
  user-agent: auto
  api-client: auto
gemini-api-key:
  - api-key: g-key
    headers:
      User-Agent: auto
      X-Trace: ok
`)
	path := filepath.Join(t.TempDir(), "config.yaml")
	if errWrite := os.WriteFile(path, raw, 0444); errWrite != nil {
		t.Fatal(errWrite)
	}
	t.Cleanup(func() { _ = os.Chmod(path, 0600) })

	cfg, errLoad := LoadConfigOptional(path, false)
	if errLoad != nil {
		t.Fatalf("LoadConfigOptional() on read-only legacy config failed: %v", errLoad)
	}
	if cfg.GeminiHeaderDefaults.UserAgent != "" || cfg.GeminiHeaderDefaults.APIClient != "" {
		t.Fatalf("expected cleared legacy GeminiHeaderDefaults, got %#v", cfg.GeminiHeaderDefaults)
	}
	if len(cfg.GeminiKey) != 1 || cfg.GeminiKey[0].Headers["X-Trace"] != "ok" {
		t.Fatalf("unexpected legacy GeminiKey headers: %#v", cfg.GeminiKey)
	}
	for name := range cfg.GeminiKey[0].Headers {
		if strings.EqualFold(name, "User-Agent") {
			t.Fatalf("expected legacy Gemini User-Agent auto header removed, got %#v", cfg.GeminiKey[0].Headers)
		}
	}

	// Non-ASCII invalid User-Agent must still fail even on startup load.
	invalidPath := filepath.Join(t.TempDir(), "invalid.yaml")
	if errWrite := os.WriteFile(invalidPath, []byte("upstream:\n  gemini:\n    header-defaults:\n      user-agent: \"bad\\nheader\"\n"), 0600); errWrite != nil {
		t.Fatal(errWrite)
	}
	if _, errInvalid := LoadConfig(invalidPath); errInvalid == nil || !strings.Contains(errInvalid.Error(), "printable ASCII") {
		t.Fatalf("expected invalid non-ASCII User-Agent to fail startup load, got %v", errInvalid)
	}
}
