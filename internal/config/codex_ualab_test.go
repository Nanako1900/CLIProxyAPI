func TestParseUALabCodexYAML(t *testing.T) {
	raw := `# Generated by UALab from local capture (tag: codex-cli, captured: 2026-11-24T17:10:43Z)
oauth:
  providers:
    codex:
      header-defaults:
        user-agent: "codex-tui/0.172.0 (Mac OS 27.3.0; arm64) Apple_Terminal/489.11 (codex-tui; 0.172.0)"
        originator: "codex-tui"
        beta-features: "remote_compaction_v2"
        accept-encoding: "zstd,gzip"
        force-http1: true
        header-order:
          - x-codex-beta-features
          - x-codex-window-id
          - x-codex-turn-metadata
          - x-client-request-id
          - session-id
          - thread-id
          - accept
          - content-type
          - authorization
          - originator
          - user-agent
          - accept-encoding
          - host
          - content-length
`
	hd, err := ParseUALabCodexYAML(raw)
	if err != nil {
		t.Fatalf("ParseUALabCodexYAML error = %v", err)
	}
	if want := "codex-tui/0.172.0 (Mac OS 27.3.0; arm64) Apple_Terminal/489.11 (codex-tui; 0.172.0)"; hd.UserAgent != want {
		t.Fatalf("UserAgent = %q, want %q", hd.UserAgent, want)
	}
	if hd.Originator != "codex-tui" {
		t.Fatalf("Originator = %q, want codex-tui", hd.Originator)
	}
	if hd.BetaFeatures != "remote_compaction_v2" {
		t.Fatalf("BetaFeatures = %q, want remote_compaction_v2", hd.BetaFeatures)
	}
	if hd.AcceptEncoding != "zstd,gzip" {
		t.Fatalf("AcceptEncoding = %q, want zstd,gzip", hd.AcceptEncoding)
	}
	if !hd.ForceHTTP1 {
		t.Fatalf("ForceHTTP1 = false, want true")
	}
	if len(hd.HeaderOrder) != 14 || hd.HeaderOrder[0] != "x-codex-beta-features" || hd.HeaderOrder[13] != "content-length" {
		t.Fatalf("unexpected HeaderOrder: %v", hd.HeaderOrder)
	}
}

func TestParseUALabCodexYAML_RejectsMissingMarkerAndAuto(t *testing.T) {
	if _, err := ParseUALabCodexYAML("oauth:\n  providers:\n    codex:\n      header-defaults:\n        user-agent: codex-tui/0.172.0\n"); err == nil {
		t.Fatal("expected error when UALab marker comment is missing")
	}
	if _, err := ParseUALabCodexYAML("# Generated by UALab\noauth:\n  providers:\n    codex:\n      header-defaults:\n        user-agent: auto\n"); err == nil {
		t.Fatal("expected error when user-agent is auto")
	}
	if _, err := ParseUALabCodexYAML("# Generated by UALab\noauth:\n  providers:\n    codex:\n      header-defaults:\n        originator: codex-tui\n"); err == nil {
		t.Fatal("expected error when user-agent is empty")
	}
}

func TestValidateUserAgents_RejectsCodexAuto(t *testing.T) {
	cfg := &Config{
		CodexHeaderDefaults: CodexHeaderDefaults{UserAgent: "auto"},
	}
	if err := cfg.ValidateUserAgents(); err == nil {
		t.Fatal("expected CodexHeaderDefaults.UserAgent=auto to be rejected")
	}

	credCfg := &Config{
		CodexKey: []CodexKey{
			{APIKey: "sk-test", Headers: map[string]string{"User-Agent": "auto"}},
		},
	}
	if err := credCfg.ValidateUserAgents(); err == nil {
		t.Fatal("expected CodexKey User-Agent=auto to be rejected")
	}
}

func TestLoadConfig_MigratesLegacyCodexAutoOnStartup(t *testing.T) {
	dir := t.TempDir()
	cfgPath := filepath.Join(dir, "config.yaml")
	raw := `config-version: 8
oauth:
  providers:
    codex:
      header-defaults:
        user-agent: auto
upstream:
  claude:
    header-defaults:
      user-agent: auto
api-keys:
  codex:
    - name: legacy
      base-url: https://api.example.invalid/v1
      headers:
        User-Agent: auto
      keys:
        - api-key: sk-codex-1
          headers:
            User-Agent: auto
`
	if err := os.WriteFile(cfgPath, []byte(raw), 0o600); err != nil {
		t.Fatalf("write config: %v", err)
	}
	cfg, err := LoadConfig(cfgPath)
	if err != nil {
		t.Fatalf("LoadConfig failed on legacy Codex auto: %v", err)
	}
	if cfg.CodexHeaderDefaults.UserAgent != "" {
		t.Fatalf("expected legacy Codex auto cleared on startup, got %q", cfg.CodexHeaderDefaults.UserAgent)
	}
	if cfg.ClaudeHeaderDefaults.UserAgent != "auto" {
		t.Fatalf("expected Claude auto preserved, got %q", cfg.ClaudeHeaderDefaults.UserAgent)
	}
	if len(cfg.CodexKey) != 1 || cfg.CodexKey[0].Headers["User-Agent"] != "" {
		t.Fatalf("expected legacy CodexKey User-Agent=auto stripped, got %+v", cfg.CodexKey)
	}
	if _, err := ParseConfigBytes([]byte(raw)); err == nil || !strings.Contains(err.Error(), "auto") {
		t.Fatalf("expected strict ParseConfigBytes to reject Codex auto, got %v", err)
	}
}
