// ValidUserAgent accepts empty defaults, "auto", and printable HTTP identities.
func ValidUserAgent(value string) bool {
	if len(value) > 1024 {
		return false
	}
	for _, c := range []byte(value) {
		if c < 32 || c > 126 {
			return false
		}
	}
	return true
}

// ValidateUserAgents rejects invalid identities before configuration is saved.
func (cfg *Config) ValidateUserAgents() error {
	if cfg == nil {
		return nil
	}
	for path, value := range map[string]string{
		"oauth.providers.codex.header-defaults.user-agent":      cfg.CodexHeaderDefaults.UserAgent,
		"oauth.providers.codex.header-defaults.originator":      cfg.CodexHeaderDefaults.Originator,
		"oauth.providers.codex.header-defaults.beta-features":   cfg.CodexHeaderDefaults.BetaFeatures,
		"oauth.providers.codex.header-defaults.accept-encoding": cfg.CodexHeaderDefaults.AcceptEncoding,
		"upstream.gemini.header-defaults.user-agent":            cfg.GeminiHeaderDefaults.UserAgent,
		"upstream.gemini.header-defaults.api-client":            cfg.GeminiHeaderDefaults.APIClient,
		"upstream.claude.header-defaults.user-agent":            cfg.ClaudeHeaderDefaults.UserAgent,
	} {
		if !ValidUserAgent(value) {
			return fmt.Errorf("%s must contain at most 1024 printable ASCII characters", path)
		}
	}
	// Gemini and Codex do not support "auto" or built-in defaults; require a pasted # Generated by UALab profile.
	if strings.EqualFold(strings.TrimSpace(cfg.GeminiHeaderDefaults.UserAgent), "auto") {
		return fmt.Errorf("upstream.gemini.header-defaults.user-agent does not support \"auto\"; paste the # Generated by UALab YAML profile")
	}
	if strings.EqualFold(strings.TrimSpace(cfg.GeminiHeaderDefaults.APIClient), "auto") {
		return fmt.Errorf("upstream.gemini.header-defaults.api-client does not support \"auto\"; paste the # Generated by UALab YAML profile")
	}
	if strings.EqualFold(strings.TrimSpace(cfg.CodexHeaderDefaults.UserAgent), "auto") {
		return fmt.Errorf("oauth.providers.codex.header-defaults.user-agent does not support \"auto\"; paste the # Generated by UALab YAML profile")
	}
	validateHeaders := func(provider string, index int, headers map[string]string) error {
		if err := validateUserAgentHeaders(headers, usesGeminiUserAgent(provider)); err != nil {
			return fmt.Errorf("%s credential %d: %w", provider, index+1, err)
		}
		return nil
	}
	for provider, keys := range map[string][]GeminiKey{"gemini": cfg.GeminiKey, "interactions": cfg.InteractionsKey} {
		for i, key := range keys {
			if errValidate := validateHeaders(provider, i, key.Headers); errValidate != nil {
				return errValidate
			}
		}
	}
	for i, key := range cfg.VertexCompatAPIKey {
		if errValidate := validateHeaders("vertex", i, key.Headers); errValidate != nil {
			return errValidate
		}
	}
	for i, key := range cfg.CodexKey {
		if errValidate := validateHeaders("codex", i, key.Headers); errValidate != nil {
			return errValidate
		}
	}
	for i, key := range cfg.ClaudeKey {
		if errValidate := validateHeaders("claude", i, key.Headers); errValidate != nil {
			return errValidate
		}
	}
	return nil
}

func usesGeminiUserAgent(provider string) bool {
	return provider == "gemini" || provider == "interactions" || provider == "vertex" || provider == "codex"
}

func validateUserAgentHeaders(headers map[string]string, rejectConflicts bool) error {
	var previous string
	var seen bool
	for name, value := range headers {
		if !strings.EqualFold(strings.TrimSpace(name), "User-Agent") {
			continue
		}
		if !ValidUserAgent(value) {
			return fmt.Errorf("User-Agent must contain at most 1024 printable ASCII characters")
		}
		if rejectConflicts {
			normalized := strings.TrimSpace(value)
			if strings.EqualFold(normalized, "auto") {
				return fmt.Errorf("User-Agent does not support \"auto\"; paste the # Generated by UALab YAML profile")
			}
			if seen && previous != normalized {
				return fmt.Errorf("conflicting User-Agent headers")
			}
			previous, seen = normalized, true
		}
	}
	return nil
}

var legacyGeminiAutoScalarPaths = []string{
	"upstream.gemini.header-defaults.user-agent",
	"upstream.gemini.header-defaults.api-client",
	"gemini-header-defaults.user-agent",
	"gemini-header-defaults.api-client",
	"oauth.providers.codex.header-defaults.user-agent",
	"codex-header-defaults.user-agent",
}

func isAutoScalarNode(node *yaml.Node) bool {
	resolved := derefConfigNode(node)
	return resolved != nil && resolved.Kind == yaml.ScalarNode && strings.EqualFold(strings.TrimSpace(resolved.Value), "auto")
}

func clearScalarNodeToEmptyString(node *yaml.Node) {
	node.Kind = yaml.ScalarNode
	node.Tag = "!!str"
	node.Value = ""
	node.Style = 0
	node.Alias = nil
	node.Content = nil
}

func headersNodeHasAutoUserAgent(node *yaml.Node) bool {
	resolved := derefConfigNode(node)
	if resolved == nil || resolved.Kind != yaml.MappingNode {
		return false
	}
	for i := 0; i+1 < len(resolved.Content); i += 2 {
		k := resolved.Content[i]
		v := resolved.Content[i+1]
		if k.Kind == yaml.ScalarNode && strings.EqualFold(strings.TrimSpace(k.Value), "User-Agent") && isAutoScalarNode(v) {
			return true
		}
	}
	return false
}

func stripAutoUserAgentFromHeaders(parent *yaml.Node) bool {
	if parent == nil || parent.Kind != yaml.MappingNode {
		return false
	}
	idx := findMapKeyIndex(parent, "headers")
	if idx < 0 || idx+1 >= len(parent.Content) {
		return false
	}
	headersNode := parent.Content[idx+1]
	if !headersNodeHasAutoUserAgent(headersNode) {
		return false
	}
	if headersNode.Kind == yaml.AliasNode {
		headersNode = deepCopyNode(derefConfigNode(headersNode))
		parent.Content[idx+1] = headersNode
	}
	filtered := make([]*yaml.Node, 0, len(headersNode.Content))
	for i := 0; i+1 < len(headersNode.Content); i += 2 {
		k := headersNode.Content[i]
		v := headersNode.Content[i+1]
		if k.Kind == yaml.ScalarNode && strings.EqualFold(strings.TrimSpace(k.Value), "User-Agent") && isAutoScalarNode(v) {
			continue
		}
		filtered = append(filtered, k, v)
	}
	headersNode.Content = filtered
	return true
}

func ensureWritableMappingNode(slot **yaml.Node) *yaml.Node {
	if slot == nil || *slot == nil {
		return nil
	}
	if (*slot).Kind == yaml.AliasNode {
		resolved := derefConfigNode(*slot)
		if resolved == nil || resolved.Kind != yaml.MappingNode {
			return nil
		}
		*slot = deepCopyNode(resolved)
	}
	if (*slot).Kind != yaml.MappingNode {
		return nil
	}
	return *slot
}

// stripLegacyGeminiAutoNodes clears deprecated Gemini "auto" User-Agent / api-client
// values from a startup YAML document so existing deployments boot cleanly instead of
// crash-looping after Gemini switched to pasted UALab profiles.
func stripLegacyGeminiAutoNodes(root *yaml.Node) []string {
	if root == nil {
		return nil
	}
	if root.Kind == yaml.DocumentNode && len(root.Content) > 0 {
		root = root.Content[0]
	}
	if root.Kind != yaml.MappingNode {
		return nil
	}

	var cleared []string
	var expanded *yaml.Node
	for _, path := range legacyGeminiAutoScalarPaths {
		if node := yamlPath(root, path); node != nil {
			if isAutoScalarNode(node) {
				clearScalarNodeToEmptyString(node)
				cleared = append(cleared, path)
			}
			continue
		}
		if expanded == nil {
			expanded = expandConfigAliases(root)
		}
		if node := yamlPath(expanded, path); isAutoScalarNode(node) {
			setYAMLPath(root, path, &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: ""})
			cleared = append(cleared, path)
		}
	}

	for _, provider := range []string{"gemini", "interactions", "vertex", "codex"} {
		groups := yamlPath(root, "api-keys."+provider)
		if groups == nil || groups.Kind != yaml.SequenceNode {
			continue
		}
		for i := range groups.Content {
			group := derefConfigNode(groups.Content[i])
			if group == nil || group.Kind != yaml.MappingNode {
				continue
			}
			if idx := findMapKeyIndex(group, "headers"); idx >= 0 && idx+1 < len(group.Content) && headersNodeHasAutoUserAgent(group.Content[idx+1]) {
				writable := ensureWritableMappingNode(&groups.Content[i])
				if stripAutoUserAgentFromHeaders(writable) {
					cleared = append(cleared, fmt.Sprintf("api-keys.%s[%d].headers.User-Agent", provider, i))
				}
				group = writable
			}
			keys := yamlPath(group, "keys")
			if keys == nil || keys.Kind != yaml.SequenceNode {
				continue
			}
			for j := range keys.Content {
				keyNode := derefConfigNode(keys.Content[j])
				if keyNode == nil || keyNode.Kind != yaml.MappingNode {
					continue
				}
				if idx := findMapKeyIndex(keyNode, "headers"); idx >= 0 && idx+1 < len(keyNode.Content) && headersNodeHasAutoUserAgent(keyNode.Content[idx+1]) {
					writableGroup := ensureWritableMappingNode(&groups.Content[i])
					writableKeys := yamlPath(writableGroup, "keys")
					if writableKeys != nil && j < len(writableKeys.Content) {
						writableKey := ensureWritableMappingNode(&writableKeys.Content[j])
						if stripAutoUserAgentFromHeaders(writableKey) {
							cleared = append(cleared, fmt.Sprintf("api-keys.%s[%d].keys[%d].headers.User-Agent", provider, i, j))
						}
					}
				}
			}
		}
	}

	for _, legacyField := range []string{"gemini-api-key", "interactions-api-key", "vertex-api-key", "codex-api-key"} {
		seq := yamlPath(root, legacyField)
		if seq == nil || seq.Kind != yaml.SequenceNode {
			continue
		}
		for i := range seq.Content {
			item := derefConfigNode(seq.Content[i])
			if item == nil || item.Kind != yaml.MappingNode {
				continue
			}
			if idx := findMapKeyIndex(item, "headers"); idx >= 0 && idx+1 < len(item.Content) && headersNodeHasAutoUserAgent(item.Content[idx+1]) {
				writable := ensureWritableMappingNode(&seq.Content[i])
				if stripAutoUserAgentFromHeaders(writable) {
					cleared = append(cleared, fmt.Sprintf("%s[%d].headers.User-Agent", legacyField, i))
				}
			}
		}
	}

	return cleared
}

func warnClearedLegacyGeminiAuto(cleared []string) {
	if len(cleared) == 0 {
		return
	}
	log.Warnf("cleared legacy Gemini/Codex \"auto\" setting(s) (%s) during startup; paste a %s YAML profile to configure headers", strings.Join(cleared, ", "), UALabGeneratedMarker)
}
