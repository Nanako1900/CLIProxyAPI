// GeminiCredentialUserAgent always returns empty because Gemini identity is
// controlled solely by the pasted "# Generated by UALab" upstream.gemini.header-defaults
// profile rather than per-credential UA overrides.
func GeminiCredentialUserAgent(_ *cliproxyauth.Auth) string {
	return ""
}

// ResolveGeminiUserAgent returns the pasted UALab User-Agent from
// cfg.GeminiHeaderDefaults. It never resolves "auto", never falls back to a
// built-in default UA, and ignores legacy credential UA overrides.
func ResolveGeminiUserAgent(_ context.Context, cfg *config.Config, _ *cliproxyauth.Auth, _ string, _ http.Header) string {
	if cfg == nil {
		return ""
	}
	ua := strings.TrimSpace(cfg.GeminiHeaderDefaults.UserAgent)
	if ua == "" || strings.EqualFold(ua, "auto") || !config.ValidUserAgent(ua) {
		return ""
	}
	return ua
}

// ApplyGeminiUserAgent applies only the pasted UALab User-Agent from
// cfg.GeminiHeaderDefaults (never "auto" and never a built-in default).
func ApplyGeminiUserAgent(req *http.Request, cfg *config.Config, auth *cliproxyauth.Auth, model string, clientHeaders http.Header) {
	if req == nil {
		return
	}
	if ua := ResolveGeminiUserAgent(req.Context(), cfg, auth, model, clientHeaders); ua != "" {
		setClientUserAgent(req.Header, ua)
	}
}

// ApplyGeminiHeaders preserves non-identity credential custom headers while
// applying Gemini identity headers (User-Agent, X-Goog-Api-Client,
// Accept-Encoding, ExtraHeaders) strictly from the pasted "# Generated by UALab"
// cfg.GeminiHeaderDefaults profile.
func ApplyGeminiHeaders(req *http.Request, cfg *config.Config, auth *cliproxyauth.Auth, model string, clientHeaders http.Header) {
	if req == nil {
		return
	}
	if auth != nil && len(auth.Attributes) > 0 {
		filtered := make(map[string]string, len(auth.Attributes))
		for key, val := range auth.Attributes {
			if isGeminiIdentityAttribute(key) {
				continue
			}
			filtered[key] = val
		}
		if len(filtered) > 0 {
			util.ApplyCustomHeadersFromAttrs(req, filtered, clientHeaders)
		}
	}

	if cfg == nil {
		return
	}
	hd := cfg.GeminiHeaderDefaults
	ApplyGeminiUserAgent(req, cfg, auth, model, clientHeaders)

	if apiClient := strings.TrimSpace(hd.APIClient); apiClient != "" && !strings.EqualFold(apiClient, "auto") && config.ValidUserAgent(apiClient) {
		req.Header.Set("X-Goog-Api-Client", apiClient)
	}
	for name, val := range hd.ExtraHeaders {
		name = strings.TrimSpace(name)
		val = strings.TrimSpace(val)
		if name == "" || val == "" || isProtectedGeminiHeader(name) {
			continue
		}
		if req.Header.Get(name) == "" {
			req.Header.Set(name, val)
		}
	}
	// Keep Go net/http's automatic gzip request + transparent decompression when
	// accept-encoding is "gzip" or omitted; only set explicitly for non-gzip values.
	if ae := strings.TrimSpace(hd.AcceptEncoding); ae != "" && !strings.EqualFold(ae, "gzip") {
		req.Header.Set("Accept-Encoding", ae)
	}
}

func isGeminiIdentityAttribute(key string) bool {
	prefix, name, ok := strings.Cut(key, ":")
	if !ok || !strings.EqualFold(prefix, "header") {
		return false
	}
	name = strings.TrimSpace(name)
	return strings.EqualFold(name, "User-Agent") || strings.EqualFold(name, "X-Goog-Api-Client")
}

func isProtectedGeminiHeader(name string) bool {
	switch strings.ToLower(strings.TrimSpace(name)) {
	case "authorization", "x-goog-api-key", "cookie", "host", "content-length", "transfer-encoding", "connection":
		return true
	default:
		return false
	}
}

const geminiOrderedTransportCacheCapacity = 64

var geminiOrderedTransportCache = internalcache.NewBoundedLRU[string, http.RoundTripper](
	geminiOrderedTransportCacheCapacity,
	func(_ string, rt http.RoundTripper) {
		if tr, ok := rt.(interface{ CloseIdleConnections() }); ok {
			tr.CloseIdleConnections()
		}
	},
)

// NewGeminiHTTPClient returns an HTTP client for Gemini upstream requests.
// When neither HeaderOrder nor ForceHTTP1 is configured in GeminiHeaderDefaults,
// it delegates directly to NewProxyAwareHTTPClient. When HeaderOrder or
// ForceHTTP1 is configured from a pasted UALab profile, it uses native Go TLS
// over HTTP/1.1 with httpwire.NewOrderedRequestConn so outgoing wire headers
// match the local capture's exact casing and order.
func NewGeminiHTTPClient(ctx context.Context, cfg *config.Config, auth *cliproxyauth.Auth, timeout time.Duration) (clientOut *http.Client) {
	if cfg == nil || (len(cfg.GeminiHeaderDefaults.HeaderOrder) == 0 && !cfg.GeminiHeaderDefaults.ForceHTTP1) {
		return NewProxyAwareHTTPClient(ctx, cfg, auth, timeout)
	}

	proxyURL := effectiveProxyURL(ctx, cfg, auth)
	if proxyURL == "" && ctx != nil {
		if rt, ok := ctx.Value("cliproxy.roundtripper").(http.RoundTripper); ok && rt != nil {
			return NewProxyAwareHTTPClient(ctx, cfg, auth, timeout)
		}
	}

	defer func() { clientOut = httptransport.Decorate(ctx, clientOut) }()

	order := append([]string(nil), cfg.GeminiHeaderDefaults.HeaderOrder...)
	cacheKey := proxyURL + "\x00" + strings.Join(order, ",")
	rt := geminiOrderedTransportCache.GetOrAdd(cacheKey, func() http.RoundTripper {
		return newGeminiOrderedTransport(proxyURL, order)
	})

	client := &http.Client{Transport: rt}
	if timeout > 0 {
		client.Timeout = timeout
	}
	return client
}

func newGeminiOrderedTransport(proxyURL string, order []string) *http.Transport {
	return newGeminiOrderedTransportForDialer(geminiDialerForProxy(proxyURL), order, nil)
}

func newGeminiOrderedTransportForDialer(dialer proxy.Dialer, order []string, tlsConfigTemplate *tls.Config) *http.Transport {
	var orderFn httpwire.RequestHeaderOrder
	if len(order) > 0 {
		copied := append([]string(nil), order...)
		orderFn = func(_, _ string) []string { return copied }
	}

	dialRaw := func(ctx context.Context, network, addr string) (net.Conn, error) {
		var (
			conn net.Conn
			err  error
		)
		if contextDialer, ok := dialer.(proxy.ContextDialer); ok {
			conn, err = contextDialer.DialContext(ctx, network, addr)
		} else {
			conn, err = dialer.Dial(network, addr)
		}
		if err != nil {
			return nil, err
		}
		return stampProxyKeepAlive(conn), nil
	}

	return &http.Transport{
		ForceAttemptHTTP2:   false,
		TLSNextProto:        make(map[string]func(authority string, c *tls.Conn) http.RoundTripper),
		MaxIdleConns:        100,
		MaxIdleConnsPerHost: 8,
		IdleConnTimeout:     90 * time.Second,
		DialContext: func(ctx context.Context, network, addr string) (net.Conn, error) {
			conn, err := dialRaw(ctx, network, addr)
			if err != nil {
				return nil, err
			}
			return httpwire.NewOrderedRequestConn(conn, orderFn), nil
		},
		DialTLSContext: func(ctx context.Context, network, addr string) (net.Conn, error) {
			conn, err := dialRaw(ctx, network, addr)
			if err != nil {
				return nil, fmt.Errorf("gemini ordered tls: dial upstream: %w", err)
			}
			host, _, errSplit := net.SplitHostPort(addr)
			if errSplit != nil {
				_ = conn.Close()
				return nil, fmt.Errorf("gemini ordered tls: split upstream address: %w", errSplit)
			}
			var tlsCfg *tls.Config
			if tlsConfigTemplate != nil {
				tlsCfg = tlsConfigTemplate.Clone()
			} else {
				tlsCfg = &tls.Config{MinVersion: tls.VersionTLS12}
			}
			if tlsCfg.ServerName == "" {
				tlsCfg.ServerName = host
			}
			tlsCfg.NextProtos = []string{"http/1.1"}

			tlsConn := tls.Client(conn, tlsCfg)
			handshakeCtx, cancelHandshake := handshakeContext(ctx)
			defer cancelHandshake()
			if errHandshake := tlsConn.HandshakeContext(handshakeCtx); errHandshake != nil {
				errHandshake = classifyHandshakeError(ctx, handshakeCtx, errHandshake)
				_ = conn.Close()
				return nil, fmt.Errorf("gemini ordered tls: handshake upstream: %w", errHandshake)
			}
			return httpwire.NewOrderedRequestConn(tlsConn, orderFn), nil
		},
	}
}

func geminiDialerForProxy(proxyURL string) proxy.Dialer {
	if strings.TrimSpace(proxyURL) != "" {
		proxyDialer, mode, errBuild := proxyutil.BuildDialer(proxyURL)
		if errBuild != nil {
			log.Errorf("gemini ordered tls: failed to configure proxy dialer for %q: %v", proxyutil.Redact(proxyURL), errBuild)
		} else if mode != proxyutil.ModeInherit && proxyDialer != nil {
			return proxyDialer
		}
	}
	return &envProxyDialer{
		direct: &net.Dialer{
			Timeout:   30 * time.Second,
			KeepAlive: proxyPoolKeepAlivePeriod,
		},
	}
}

type envProxyDialer struct {
	direct *net.Dialer
}

func (d *envProxyDialer) Dial(network, addr string) (net.Conn, error) {
	return d.DialContext(context.Background(), network, addr)
}

func (d *envProxyDialer) DialContext(ctx context.Context, network, addr string) (net.Conn, error) {
	probeURL := &url.URL{Scheme: "https", Host: addr}
	if pURL, err := http.ProxyFromEnvironment(&http.Request{URL: probeURL}); err == nil && pURL != nil {
		if proxyDialer, mode, errBuild := proxyutil.BuildDialer(pURL.String()); errBuild == nil && mode != proxyutil.ModeInherit && proxyDialer != nil {
			if cd, ok := proxyDialer.(proxy.ContextDialer); ok {
				return cd.DialContext(ctx, network, addr)
			}
			return proxyDialer.Dial(network, addr)
		}
	}
	return d.direct.DialContext(ctx, network, addr)
}
