// CodexCredentialUserAgent returns a validated static per-credential
// header:User-Agent override when explicitly configured on the credential.
// Empty values, "auto", template variables, or invalid header values are ignored
// so credentials without an explicit override strictly inherit global defaults.
func CodexCredentialUserAgent(auth *cliproxyauth.Auth) string {
	return codexCredentialHeaderOverride(auth, "User-Agent", true)
}

func codexCredentialHeaderOverride(auth *cliproxyauth.Auth, headerName string, rejectAuto bool) string {
	if auth == nil || len(auth.Attributes) == 0 {
		return ""
	}
	canonicalKey := "header:" + headerName
	var bestKey, bestVal string
	for key, raw := range auth.Attributes {
		prefix, name, ok := strings.Cut(key, ":")
		if !ok || !strings.EqualFold(prefix, "header") || !strings.EqualFold(strings.TrimSpace(name), headerName) {
			continue
		}
		val := strings.TrimSpace(raw)
		if val == "" || !config.ValidUserAgent(val) {
			continue
		}
		if strings.HasPrefix(val, "$") || strings.Contains(strings.ToUpper(val), "$CPA-SESSION-ID") {
			continue
		}
		if rejectAuto && strings.EqualFold(val, "auto") {
			continue
		}
		if key == canonicalKey {
			return val
		}
		if bestKey == "" || key < bestKey {
			bestKey, bestVal = key, val
		}
	}
	return bestVal
}

// ResolveCodexHeaderDefaultsForAuth returns the effective Codex UALab header
// defaults for auth: global cfg.CodexHeaderDefaults overlaid with any validated
// per-credential header overrides (User-Agent, Originator, X-Codex-Beta-Features,
// Accept-Encoding). Credentials without overrides inherit global defaults verbatim.
func ResolveCodexHeaderDefaultsForAuth(cfg *config.Config, auth *cliproxyauth.Auth) config.CodexHeaderDefaults {
	var hd config.CodexHeaderDefaults
	if cfg != nil {
		hd = cfg.CodexHeaderDefaults
	}
	if auth == nil {
		return hd
	}
	if ua := codexCredentialHeaderOverride(auth, "User-Agent", true); ua != "" {
		hd.UserAgent = ua
	}
	if originator := codexCredentialHeaderOverride(auth, "Originator", false); originator != "" {
		hd.Originator = originator
	}
	if beta := codexCredentialHeaderOverride(auth, "X-Codex-Beta-Features", false); beta != "" {
		hd.BetaFeatures = beta
	}
	if ae := codexCredentialHeaderOverride(auth, "Accept-Encoding", false); ae != "" {
		hd.AcceptEncoding = ae
	}
	return hd
}

// ResolveCodexUserAgent returns the pasted UALab User-Agent from
// cfg.CodexHeaderDefaults. It never resolves "auto" and never falls back to a
// built-in default UA.
func ResolveCodexUserAgent(cfg *config.Config) string {
	return ResolveCodexUserAgentForAuth(cfg, nil)
}

// ResolveCodexUserAgentForAuth returns the effective Codex User-Agent for auth
// (per-credential header:User-Agent override > global cfg.CodexHeaderDefaults.UserAgent).
// It never resolves "auto" and never falls back to a built-in default UA.
func ResolveCodexUserAgentForAuth(cfg *config.Config, auth *cliproxyauth.Auth) string {
	hd := ResolveCodexHeaderDefaultsForAuth(cfg, auth)
	ua := strings.TrimSpace(hd.UserAgent)
	if ua == "" || strings.EqualFold(ua, "auto") || !config.ValidUserAgent(ua) {
		return ""
	}
	return ua
}

// IsCodexIdentityAttribute reports whether a credential attribute targets
// Codex identity headers managed through ResolveCodexHeaderDefaultsForAuth.
func IsCodexIdentityAttribute(key string) bool {
	prefix, name, ok := strings.Cut(key, ":")
	if !ok || !strings.EqualFold(prefix, "header") {
		return false
	}
	switch strings.ToLower(strings.TrimSpace(name)) {
	case "user-agent", "originator", "x-codex-beta-features", "accept-encoding":
		return true
	default:
		return false
	}
}

// ApplyCodexUALabHeaders applies the global pasted "# Generated by UALab" Codex
// profile to outgoing HTTP request headers.
func ApplyCodexUALabHeaders(headers http.Header, cfg *config.Config) {
	ApplyCodexUALabHeadersForAuth(headers, cfg, nil)
}

// ApplyCodexUALabHeadersForAuth applies the effective Codex UALab profile
// (global cfg overlaid with any validated per-credential overrides on auth)
// to outgoing HTTP request headers. It never resolves "auto" and never injects
// a hardcoded default UA when unconfigured.
func ApplyCodexUALabHeadersForAuth(headers http.Header, cfg *config.Config, auth *cliproxyauth.Auth) {
	if headers == nil {
		return
	}
	hd := ResolveCodexHeaderDefaultsForAuth(cfg, auth)
	applyCodexUALabCoreHeaders(headers, hd)
	if ae := strings.TrimSpace(hd.AcceptEncoding); ae != "" && config.ValidUserAgent(ae) {
		setHeaderFolded(headers, "Accept-Encoding", ae)
	}
	if len(hd.HeaderOrder) > 0 && !headerOrderContains(hd.HeaderOrder, "Connection") {
		deleteHeaderFolded(headers, "Connection")
	}
}

// ApplyCodexUALabWebsocketHeaders applies the global pasted "# Generated by UALab"
// Codex identity headers suitable for WebSocket upgrade requests.
func ApplyCodexUALabWebsocketHeaders(headers http.Header, cfg *config.Config) {
	ApplyCodexUALabWebsocketHeadersForAuth(headers, cfg, nil)
}

// ApplyCodexUALabWebsocketHeadersForAuth applies the effective Codex UALab
// identity headers (global cfg overlaid with any validated per-credential
// overrides on auth) suitable for WebSocket upgrade requests (omitting
// Accept-Encoding and Connection mutations).
func ApplyCodexUALabWebsocketHeadersForAuth(headers http.Header, cfg *config.Config, auth *cliproxyauth.Auth) {
	if headers == nil {
		return
	}
	hd := ResolveCodexHeaderDefaultsForAuth(cfg, auth)
	applyCodexUALabCoreHeaders(headers, hd)
}

func applyCodexUALabCoreHeaders(headers http.Header, hd config.CodexHeaderDefaults) {
	if ua := strings.TrimSpace(hd.UserAgent); ua != "" && !strings.EqualFold(ua, "auto") && config.ValidUserAgent(ua) {
		setClientUserAgent(headers, ua)
	}
	if originator := strings.TrimSpace(hd.Originator); originator != "" && config.ValidUserAgent(originator) {
		setHeaderFolded(headers, "Originator", originator)
	}
	if beta := strings.TrimSpace(hd.BetaFeatures); beta != "" && config.ValidUserAgent(beta) {
		setHeaderFolded(headers, "X-Codex-Beta-Features", beta)
	}
	for name, val := range hd.ExtraHeaders {
		name = strings.TrimSpace(name)
		val = strings.TrimSpace(val)
		if name == "" || val == "" || isProtectedCodexHeader(name) {
			continue
		}
		if HeaderValueCaseInsensitive(headers, name) == "" {
			headers.Set(name, val)
		}
	}
}

func setHeaderFolded(headers http.Header, canonical, value string) {
	deleteHeaderFolded(headers, canonical)
	headers.Set(canonical, value)
}

func deleteHeaderFolded(headers http.Header, name string) {
	for existing := range headers {
		if strings.EqualFold(existing, name) {
			delete(headers, existing)
		}
	}
}

func headerOrderContains(order []string, target string) bool {
	for _, name := range order {
		if strings.EqualFold(strings.TrimSpace(name), target) {
			return true
		}
	}
	return false
}

func isProtectedCodexHeader(name string) bool {
	switch strings.ToLower(strings.TrimSpace(name)) {
	case "authorization", "cookie", "host", "content-length", "transfer-encoding", "connection",
		"x-oai-attestation", "x-codex-turn-metadata", "x-codex-window-id", "x-client-request-id",
		"session-id", "session_id", "thread-id", "conversation_id":
		return true
	default:
		return false
	}
}

const codexOrderedTransportCacheCapacity = 64

var codexOrderedTransportCache = internalcache.NewBoundedLRU[string, http.RoundTripper](
	codexOrderedTransportCacheCapacity,
	func(_ string, rt http.RoundTripper) {
		if tr, ok := rt.(interface{ CloseIdleConnections() }); ok {
			tr.CloseIdleConnections()
		}
	},
)

// NewCodexHTTPClient returns an HTTP client for Codex upstream requests.
// When neither HeaderOrder nor ForceHTTP1 is configured in CodexHeaderDefaults,
// it delegates directly to NewUtlsHTTPClient. When HeaderOrder or ForceHTTP1 is
// configured from a pasted UALab profile, it sends HTTP/1.1 requests with
// httpwire.NewOrderedRequestConn so outgoing wire headers match the local
// capture's exact lowercase casing and order (preserving a Chrome HTTP/1.1 TLS
// ClientHello for chatgpt.com).
func NewCodexHTTPClient(ctx context.Context, cfg *config.Config, auth *cliproxyauth.Auth, timeout time.Duration) (clientOut *http.Client) {
	if cfg == nil || (len(cfg.CodexHeaderDefaults.HeaderOrder) == 0 && !cfg.CodexHeaderDefaults.ForceHTTP1) {
		return NewUtlsHTTPClient(ctx, cfg, auth, timeout)
	}

	proxyURL := effectiveProxyURL(ctx, cfg, auth)
	if proxyURL == "" && ctx != nil {
		if rt, ok := ctx.Value("cliproxy.roundtripper").(http.RoundTripper); ok && rt != nil {
			return NewUtlsHTTPClient(ctx, cfg, auth, timeout)
		}
	}

	handshakeTimeout := cfg.TLSHandshakeTimeout()
	defer func() {
		clientOut = httptransport.Decorate(ctx, clientOut)
		if clientOut != nil && handshakeTimeout > 0 {
			clientOut.Transport = &tlsHandshakeTimeoutRoundTripper{base: clientOut.Transport, timeout: handshakeTimeout}
		}
	}()

	order := append([]string(nil), cfg.CodexHeaderDefaults.HeaderOrder...)
	cacheKey := proxyURL + "\x00" + strings.Join(order, ",")
	rt := codexOrderedTransportCache.GetOrAdd(cacheKey, func() http.RoundTripper {
		return newCodexOrderedTransport(proxyURL, order)
	})

	client := &http.Client{Transport: rt}
	if timeout > 0 {
		client.Timeout = timeout
	}
	return client
}

func newCodexOrderedTransport(proxyURL string, order []string) *http.Transport {
	return newCodexOrderedTransportForDialer(geminiDialerForProxy(proxyURL), order, nil)
}

var codexAPICallTransportCache = internalcache.NewBoundedLRU[string, http.RoundTripper](
	codexOrderedTransportCacheCapacity,
	func(_ string, rt http.RoundTripper) {
		if tr, ok := rt.(interface{ CloseIdleConnections() }); ok {
			tr.CloseIdleConnections()
		}
	},
)

// NewCodexAPICallTransport returns an HTTP/1.1 transport for management APICall
// requests targeting Codex/ChatGPT (e.g. wham/usage, subscriptions, reset
// credits). It applies the pasted UALab HeaderOrder, uses Chrome HTTP/1.1 ALPN
// uTLS for chatgpt.com, never reads environment proxies, and fails closed on
// invalid proxy configurations to prevent IP leakage.
func NewCodexAPICallTransport(cfg *config.Config, proxyURL string) http.RoundTripper {
	var order []string
	if cfg != nil && len(cfg.CodexHeaderDefaults.HeaderOrder) > 0 {
		order = append([]string(nil), cfg.CodexHeaderDefaults.HeaderOrder...)
	}
	cacheKey := strings.TrimSpace(proxyURL) + "\x00" + strings.Join(order, ",")
	return codexAPICallTransportCache.GetOrAdd(cacheKey, func() http.RoundTripper {
		return newCodexOrderedTransportForDialer(strictAPICallDialerForProxy(proxyURL), order, nil)
	})
}

func newCodexOrderedTransportForDialer(dialer proxy.Dialer, order []string, tlsConfigTemplate *tls.Config) *http.Transport {
	var orderFn httpwire.RequestHeaderOrder
	if len(order) > 0 {
		copied := append([]string(nil), order...)
		orderFn = func(_, _ string) []string { return copied }
	}

	dialRaw := func(ctx context.Context, network, addr string) (net.Conn, error) {
		var (
			conn net.Conn
			err  error
		)
		if contextDialer, ok := dialer.(proxy.ContextDialer); ok {
			conn, err = contextDialer.DialContext(ctx, network, addr)
		} else {
			conn, err = dialer.Dial(network, addr)
		}
		if err != nil {
			return nil, err
		}
		return stampProxyKeepAlive(conn), nil
	}

	return &http.Transport{
		ForceAttemptHTTP2:   false,
		TLSNextProto:        make(map[string]func(authority string, c *tls.Conn) http.RoundTripper),
		MaxIdleConns:        100,
		MaxIdleConnsPerHost: 8,
		IdleConnTimeout:     90 * time.Second,
		DialContext: func(ctx context.Context, network, addr string) (net.Conn, error) {
			conn, err := dialRaw(ctx, network, addr)
			if err != nil {
				return nil, err
			}
			return httpwire.NewOrderedRequestConn(conn, orderFn), nil
		},
		DialTLSContext: func(ctx context.Context, network, addr string) (net.Conn, error) {
			conn, err := dialRaw(ctx, network, addr)
			if err != nil {
				return nil, fmt.Errorf("codex ordered tls: dial upstream: %w", err)
			}
			host, _, errSplit := net.SplitHostPort(addr)
			if errSplit != nil {
				_ = conn.Close()
				return nil, fmt.Errorf("codex ordered tls: split upstream address: %w", errSplit)
			}
			if tlsConfigTemplate == nil && strings.EqualFold(host, "chatgpt.com") {
				uconn, errUTLS := dialCodexChatGPTHTTP1TLS(ctx, conn, host)
				if errUTLS != nil {
					_ = conn.Close()
					return nil, errUTLS
				}
				return httpwire.NewOrderedRequestConn(uconn, orderFn), nil
			}
			var tlsCfg *tls.Config
			if tlsConfigTemplate != nil {
				tlsCfg = tlsConfigTemplate.Clone()
			} else {
				tlsCfg = &tls.Config{MinVersion: tls.VersionTLS12}
			}
			if tlsCfg.ServerName == "" {
				tlsCfg.ServerName = host
			}
			tlsCfg.NextProtos = []string{"http/1.1"}

			tlsConn := tls.Client(conn, tlsCfg)
			handshakeCtx, cancelHandshake := handshakeContext(ctx)
			defer cancelHandshake()
			if errHandshake := tlsConn.HandshakeContext(handshakeCtx); errHandshake != nil {
				errHandshake = classifyHandshakeError(ctx, handshakeCtx, errHandshake)
				_ = conn.Close()
				return nil, fmt.Errorf("codex ordered tls: handshake upstream: %w", errHandshake)
			}
			return httpwire.NewOrderedRequestConn(tlsConn, orderFn), nil
		},
	}
}

func dialCodexChatGPTHTTP1TLS(ctx context.Context, conn net.Conn, host string) (net.Conn, error) {
	spec, errSpec := utlstls.UTLSIdToSpec(utlstls.HelloChrome_Auto)
	if errSpec != nil {
		return nil, fmt.Errorf("codex ordered tls: build chrome spec: %w", errSpec)
	}
	for _, ext := range spec.Extensions {
		if alpn, ok := ext.(*utlstls.ALPNExtension); ok {
			alpn.AlpnProtocols = []string{"http/1.1"}
		}
	}
	uconn := utlstls.UClient(conn, &utlstls.Config{ServerName: host}, utlstls.HelloCustom)
	if errPreset := uconn.ApplyPreset(&spec); errPreset != nil {
		return nil, fmt.Errorf("codex ordered tls: apply chrome http/1.1 preset: %w", errPreset)
	}
	handshakeCtx, cancelHandshake := handshakeContext(ctx)
	defer cancelHandshake()
	if errHandshake := uconn.HandshakeContext(handshakeCtx); errHandshake != nil {
		errHandshake = classifyHandshakeError(ctx, handshakeCtx, errHandshake)
		return nil, fmt.Errorf("codex ordered tls: handshake upstream: %w", errHandshake)
	}
	return uconn, nil
}
